// 写真の代替テキスト (altJa / altZh) 生成の system prompt。
// アプリ側 (lib/photo-alt.ts) と一括スクリプト (scripts/backfill-alt.mjs) の
// 両方から import するため、型注釈のない素の ESM (.mjs) で置いている
// (スクリプトは Node 単体で動き、.ts を import できない)。
// トーン・ルールの調整はこのファイルだけで完結させる。

